FROM (
    SELECT * 
    FROM soldiers 
    ORDER BY soldier_id DESC 
    LIMIT 10
) AS recent_10
ORDER BY soldier_id ASC;

-- C3: The soldiers whose ID is 10, 15 or 20 using IN
