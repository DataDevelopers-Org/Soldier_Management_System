-- -----------------------------------------------------------------------------
-- PART A: CREATE TABLES
-- -----------------------------------------------------------------------------

CREATE TABLE ranks (
    rank_id INT PRIMARY KEY,
    rank_name VARCHAR(50) NOT NULL UNIQUE,
    rank_level INT CHECK (rank_level BETWEEN 1 AND 6)
);

CREATE TABLE units (
    unit_id INT PRIMARY KEY,
    unit_name VARCHAR(100) NOT NULL UNIQUE,
    location VARCHAR(100) NOT NULL
);

CREATE TABLE missions (
    mission_id INT PRIMARY KEY,
    mission_name VARCHAR(100) NOT NULL UNIQUE,
    start_date DATE NOT NULL,
    end_date DATE,
    CONSTRAINT chk_end_date CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE soldiers (
    soldier_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_number VARCHAR(50) NOT NULL UNIQUE,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    date_of_birth DATE NOT NULL,
    enlistment_date DATE NOT NULL,
    status VARCHAR(20) DEFAULT 'Active' CHECK (status IN ('Active', 'On Leave', 'Retired')),
    rank_id INT NOT NULL,
    unit_id INT NOT NULL,
    CONSTRAINT fk_soldier_rank FOREIGN KEY (rank_id) REFERENCES ranks(rank_id),
    CONSTRAINT fk_soldier_unit FOREIGN KEY (unit_id) REFERENCES units(unit_id),
    CONSTRAINT chk_enlistment_age CHECK (enlistment_date > date_of_birth)
);

CREATE TABLE soldier_missions (
    soldier_id INT,
    mission_id INT,
    mission_role VARCHAR(100) NOT NULL,
    PRIMARY KEY (soldier_id, mission_id),
    CONSTRAINT fk_sm_soldier FOREIGN KEY (soldier_id) REFERENCES soldiers(soldier_id) ON DELETE CASCADE,
    CONSTRAINT fk_sm_mission FOREIGN KEY (mission_id) REFERENCES missions(mission_id) ON DELETE CASCADE
);

